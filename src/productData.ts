export function productImage(product: Pick<Product, 'sku' | 'category'> & { image?: string }) {
  if (product.image) return product.image
  return productImagesBySku[product.sku] ?? categoryImages[product.category] ?? `/images/products/${product.sku}.jpg`
}

export function productBrand(product: Pick<Product, 'sku' | 'supplier' | 'name'>) {
  if (productBrandsBySku[product.sku]) return productBrandsBySku[product.sku]
  return product.supplier
}

export function productDisplayName(product: Pick<Product, 'sku' | 'name'>, lang: 'ta' | 'en') {
  if (lang === 'ta' && productTamilNamesBySku[product.sku]) {
    return productTamilNamesBySku[product.sku]
  }
  return product.name
}
